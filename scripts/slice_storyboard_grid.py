#!/usr/bin/env python3
"""
slice_storyboard_grid.py
------------------------
Utility to slice a multi-panel storyboard grid image generated by an LLM/Diffusion model
into individual panel images and automatically vectorize each into scalable SVGs.

Supports:
  - Standard grid layouts (2x4, 3x3, 2x3, 1x7 horizontal strip)
  - Automatic gutter/border trimming
  - Direct conversion to SVGs via scripts/vectorize_story_panel.py

Usage:
  python3 scripts/slice_storyboard_grid.py --input grid.jpg --story crow_and_water_pot --layout 2x4 --panels 7
  python3 scripts/slice_storyboard_grid.py --input grid.jpg --story crow_and_water_pot --layout 3x3 --panels 7
"""

import sys
import os
import argparse
from PIL import Image

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VECTORIZE_SCRIPT = os.path.join(ROOT_DIR, 'scripts', 'vectorize_story_panel.py')

def slice_grid(image_path, story_id, rows, cols, total_panels, padding_pct=0.03):
    if not os.path.exists(image_path):
        print(f"Error: Grid image '{image_path}' not found.")
        return False

    out_dir = os.path.join(ROOT_DIR, 'src', 'ui', 'data', 'svgs', story_id)
    os.makedirs(out_dir, exist_ok=True)

    im = Image.open(image_path)
    w, h = im.size
    cell_w = w / cols
    cell_h = h / rows

    print(f"Slicing '{os.path.basename(image_path)}' ({w}x{h}) into {rows}x{cols} grid ({total_panels} panels)...")

    panel_idx = 1
    for r in range(rows):
        for c in range(cols):
            if panel_idx > total_panels:
                break

            # Calculate cell bounding box
            x1 = int(c * cell_w)
            y1 = int(r * cell_h)
            x2 = int((c + 1) * cell_w)
            y2 = int((r + 1) * cell_h)

            # Apply inner padding to remove border lines/gutters
            pad_x = int(cell_w * padding_pct)
            pad_y = int(cell_h * padding_pct)
            crop_box = (x1 + pad_x, y1 + pad_y, x2 - pad_x, y2 - pad_y)

            cell_crop = im.crop(crop_box)

            # Save sliced panel image
            png_name = f"panel_{panel_idx}.png"
            png_path = os.path.join(out_dir, png_name)
            cell_crop.save(png_path)

            # Vectorize to SVG
            svg_name = f"panel_{panel_idx}.svg"
            svg_path = os.path.join(out_dir, svg_name)
            cmd = f"/usr/bin/python3 \"{VECTORIZE_SCRIPT}\" \"{png_path}\" \"{svg_path}\""
            os.system(cmd)

            print(f"  ✓ Panel {panel_idx}: saved and vectorized -> {svg_name}")
            panel_idx += 1

    print(f"✓ All {total_panels} panels successfully extracted and vectorized to {out_dir}")
    return True

def main():
    parser = argparse.ArgumentParser(description="Slice Storyboard Grid Image into SVGs")
    parser.add_argument("--input", required=True, help="Input grid image path")
    parser.add_argument("--story", required=True, help="Story ID (e.g. crow_and_water_pot)")
    parser.add_argument("--layout", default="2x4", help="Grid layout (e.g. 2x4, 3x3, 2x3)")
    parser.add_argument("--panels", type=int, default=7, help="Number of panels to extract")
    parser.add_argument("--padding", type=float, default=0.03, help="Inner padding fraction (0.0 to 0.1)")
    args = parser.parse_args()

    parts = args.layout.lower().split('x')
    rows, cols = int(parts[0]), int(parts[1])

    slice_grid(args.input, args.story, rows, cols, args.panels, args.padding)

if __name__ == '__main__':
    main()
